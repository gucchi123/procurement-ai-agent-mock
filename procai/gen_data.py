def _dump(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1, sort_keys=False)
        f.write("\n")


def build(data_dir, gold_dir):
    _dump(os.path.join(data_dir, "company.json"), COMPANY)
    _dump(os.path.join(data_dir, "suppliers.json"), {"suppliers": SUPPLIERS, "tier2": TIER2})
    _dump(os.path.join(data_dir, "items.json"), ITEMS)
    _dump(os.path.join(data_dir, "network.json"), {"products": PRODUCTS, "customers": CUSTOMERS, "sources": SOURCES})
